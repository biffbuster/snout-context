#!/usr/bin/env python3
"""Build hooks/sprite.ts from art/snout.frames.txt.

Each terminal cell holds two stacked pixels using half-block glyphs:
  top+bottom colored  -> U+2580 (upper half), fg=top, bg=bottom
  top only            -> U+2580, fg=top, bg=default
  bottom only         -> U+2584 (lower half), fg=bottom, bg=default
  neither             -> space, default colors

Outputs, per frame:
  cells: base64 of little-endian u32 triplets [codePoint, fg, bg] for Raster
  lines: text runs [text, fg|null, bg|null] for surfaces without Raster

Usage: python3 art/build-sprite.py
"""
import base64
import json
import pathlib
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "art" / "snout.frames.txt"
OUT = ROOT / "hooks" / "sprite.ts"

DEFAULT = 0x01000000
UPPER, LOWER, SPACE = 0x2580, 0x2584, 0x20


def parse(text):
    palette, frames, cur = {}, {}, None
    mode = None
    for raw in text.splitlines():
        line = raw.rstrip()
        if not line or line.lstrip().startswith("#"):
            continue
        if line == "palette:":
            mode = "palette"
            continue
        if line.startswith("== "):
            mode = "frame"
            cur = line[3:].strip()
            frames[cur] = []
            continue
        if mode == "palette":
            parts = line.split()
            palette[parts[0]] = int(parts[1].lstrip("#"), 16)
        elif mode == "frame":
            frames[cur].append(line.strip())
    return palette, frames


def check(name, grid, width, height):
    if len(grid) != height:
        sys.exit(f"frame {name}: {len(grid)} rows, expected {height}")
    for i, row in enumerate(grid):
        if len(row) != width:
            sys.exit(f"frame {name} row {i}: {len(row)} cols, expected {width}")


def pad(grid, width, top, bottom):
    blank = "." * width
    return [blank] * top + grid + [blank] * bottom


def pack(grid, palette):
    width = len(grid[0])
    words, lines = [], []
    for r in range(0, len(grid), 2):
        top_row, bot_row = grid[r], grid[r + 1]
        runs = []
        for c in range(width):
            t = palette.get(top_row[c])
            b = palette.get(bot_row[c])
            if t is not None:
                cp, fg, bg = UPPER, t, (b if b is not None else DEFAULT)
            elif b is not None:
                cp, fg, bg = LOWER, b, DEFAULT
            else:
                cp, fg, bg = SPACE, DEFAULT, DEFAULT
            words += [cp, fg, bg]
            hx = lambda v: None if v == DEFAULT else f"#{v:06X}"
            key = (hx(fg) if cp != SPACE else None, hx(bg))
            ch = chr(cp)
            if runs and (runs[-1][1], runs[-1][2]) == key:
                runs[-1][0] += ch
            else:
                runs.append([ch, key[0], key[1]])
        lines.append(runs)
    cells = base64.b64encode(struct.pack(f"<{len(words)}I", *words)).decode()
    return cells, lines


def main():
    palette, frames = parse(SRC.read_text(encoding="utf-8"))
    palette.pop(".", None)
    width, height = 20, 24
    for name, grid in frames.items():
        check(name, grid, width, height)

    built = {}
    for name, grid in frames.items():
        built[name] = pack(pad(grid, width, 1, 1), palette)
    # hop: idle lifted one pixel
    built["hop"] = pack(pad(frames["idle"], width, 0, 2), palette)

    rows = (height + 2) // 2
    out = [
        "// Generated by art/build-sprite.py from art/snout.frames.txt. Do not edit.",
        "",
        "export type Run = [text: string, fg: string | null, bg: string | null]",
        "export type Frame = { cells: string; lines: Run[][] }",
        "",
        f"export const COLUMNS = {width}",
        f"export const ROWS = {rows}",
        "",
        "export const FRAMES = {",
    ]
    for name, (cells, lines) in built.items():
        out.append(f"  {name}: {{")
        out.append(f"    cells: {json.dumps(cells)},")
        out.append(f"    lines: {json.dumps(lines, ensure_ascii=False)} as Run[][],")
        out.append("  },")
    out += [
        "} satisfies Record<string, Frame>",
        "",
        "export type FrameName = keyof typeof FRAMES",
        "",
    ]
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(built)} frames, {width}x{rows} cells")


if __name__ == "__main__":
    main()
