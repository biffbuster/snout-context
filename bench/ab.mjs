/**
 * One Codex run. A throwaway CODEX_HOME trusts only this fixture (Codex loads project hooks
 * only in a trusted folder) and links the user's existing sign-in, so the real ~/.codex is
 * never touched. The result is shaped like Claude's so the rest of the harness is shared.
 */
function runCodex(task, dir) {
  const home = mkdtempSync(join(tmpdir(), "snout-ab-codexhome-"));
  symlinkSync(join(homedir(), ".codex", "auth.json"), join(home, "auth.json"));
  writeFileSync(join(home, "config.toml"), `[projects."${realpathSync(dir)}"]\ntrust_level = "trusted"\n`);
  const argv = ["exec", "--json", "-s", "workspace-write", "--dangerously-bypass-hook-trust", "--skip-git-repo-check", "-C", dir];
  if (MODEL !== "codex-default") argv.push("-m", MODEL);
  argv.push(TASKS[task].prompt);
  const r = spawnSync("codex", argv, { cwd: dir, encoding: "utf8", timeout: 15 * 60_000, env: { ...process.env, CODEX_HOME: home }, maxBuffer: 64 * 1024 * 1024 });
  rmSync(home, { recursive: true, force: true });
  let input = 0, cached = 0, output = 0, turns = 0, error, final = "";
  for (const line of (r.stdout || "").split("\n")) {
    if (!line.trim()) continue;
    let e;
    try { e = JSON.parse(line); } catch { continue; }
    if (e.type === "turn.completed" && e.usage) {
      input += e.usage.input_tokens ?? 0;
      cached += e.usage.cached_input_tokens ?? 0;
      output += (e.usage.output_tokens ?? 0) + (e.usage.reasoning_output_tokens ?? 0);
    } else if (e.type === "item.completed" && e.item?.type === "command_execution") turns++;
    else if (e.type === "item.completed" && e.item?.type === "agent_message") final = e.item.text ?? final;
    else if (e.type === "error" || e.type === "turn.failed") error = String(e.message ?? e.error?.message ?? e.type);
  }
  if (!input && !error) error = (r.stderr || "no output").slice(0, 200);
  return {
    is_error: !!error && !input,
    result: error ?? final,
    num_turns: turns,
    total_cost_usd: 0,
    usage: { input_tokens: input - cached, cache_read_input_tokens: cached, output_tokens: output },
    effTokens: Math.round(input - cached + cached * 0.1 + output),
  };
}

function runOne(task, arm) {
  const dir = makeFixture(arm);
  const started = Date.now();
  const r = AGENT === "codex" ? null : spawnSync(
    "claude",
    [
      "-p", TASKS[task].prompt,
      "--output-format", "json",
      "--model", MODEL,
      "--setting-sources", "project",
      "--strict-mcp-config",
      "--permission-mode", "acceptEdits",
      ...(TASKS[task].mcp ? ["--mcp-config", join(dir, ".mcp.json")] : []),
      "--allowedTools", "Read", "Edit", "Write", "Grep", "Glob", "Bash(node:*)", "Bash(ls:*)", "Bash(cat:*)", "Bash(grep:*)", "Bash(head:*)", "Bash(npm ls:*)", "mcp__issues__list_issues",
      "--max-budget-usd", BUDGET,
    ],
    { cwd: dir, encoding: "utf8", timeout: 15 * 60_000, env: { ...process.env, SNOUT_MODE: arm === "enforce" ? "enforce" : "observe" }, maxBuffer: 64 * 1024 * 1024 },
  );
  let out = {};
  if (AGENT === "codex") out = runCodex(task, dir);
  else {
    try {
      out = JSON.parse(r.stdout);
    } catch {
      out = { is_error: true, result: (r.stderr || r.stdout || "").slice(0, 300) };
    }
  }
  const u = out.usage ?? {};
  // Attributable numbers, from snout's own ledger in the fixture: low-value tokens the agent
  // actually read, and tokens the gate withheld. Whole-run input tokens swing by tens of
  // thousands between identical runs, so these are what isolate snout's effect.
  let denials = 0, trims = 0, lowValueRead = 0, withheld = 0;
  const ledger = join(dir, ".snout/ledger.jsonl");
  if (existsSync(ledger)) {
    for (const l of readFileSync(ledger, "utf8").split("\n")) {
      if (!l.trim()) continue;
      const d = JSON.parse(l);
      // A trimmed read withholds the cut and still puts its head into context.
      if (d.trimmed) { trims++; withheld += d.tokensAvoidedEst || 0; lowValueRead += d.tokensReadEst || 0; }
      else if (d.decision === "deny") { denials++; withheld += d.tokensAvoidedEst || 0; }
      else lowValueRead += d.tokensAvoidedEst || 0;
    }
  }
  const row = {
    task, arm,
    pass: !out.is_error && TASKS[task].check(dir),
    error: out.is_error ? String(out.result ?? out.subtype ?? "error").slice(0, 200) : undefined,
    inputTokens: (u.input_tokens ?? 0) + (u.cache_creation_input_tokens ?? 0) + (u.cache_read_input_tokens ?? 0),
    // The split matters more than the sum: cache writes cost 1.25–2× input, reads 0.1×.
    uncached: u.input_tokens ?? 0,
    cacheWrite: u.cache_creation_input_tokens ?? 0,
    cacheRead: u.cache_read_input_tokens ?? 0,
    outputTokens: u.output_tokens ?? 0,
    turns: out.num_turns ?? 0,
    costUsd: out.total_cost_usd ?? 0,
    ...(out.effTokens !== undefined ? { effTokens: out.effTokens } : {}),
    denials,
    trims,
    lowValueRead,
    withheld,
    seconds: Math.round((Date.now() - started) / 1000),
  };
  // A failed run keeps the agent's last words, so the reason survives the deleted fixture.
  if (!row.pass) row.final = String(out.result ?? "").slice(0, 500);
  if (!args.keep) rmSync(dir, { recursive: true, force: true });
  else row.dir = dir;
  return row;
}

const median = (xs) => {
  const s = [...xs].sort((a, b) => a - b);
  return s.length ? (s.length % 2 ? s[(s.length - 1) / 2] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2) : 0;
};

function main() {
  if (typeof args.summarize === "string") {
    const saved = JSON.parse(readFileSync(args.summarize, "utf8"));
    return summarize(saved.rows, [...new Set(saved.rows.map((r) => r.task))], saved.model, saved.n);
  }
  const tasks = typeof args.tasks === "string" ? args.tasks.split(",") : Object.keys(TASKS);
  const plan = [];
  for (let i = 0; i < N; i++) for (const t of tasks) for (const a of ARMS) plan.push([t, a]);
  console.error(`${plan.length} run(s): ${tasks.length} task(s) × ${ARMS.length} arm(s) × ${N}, ${AGENT}, model ${MODEL}${AGENT === "claude" ? `, cap $${BUDGET}/run` : ""}`);

  const rows = [];
  plan.forEach(([t, a], i) => {
    process.stderr.write(`[${i + 1}/${plan.length}] ${t} · ${a} ... `);
    const row = runOne(t, a);
    rows.push(row);
    process.stderr.write(`${row.pass ? "pass" : "FAIL"} · ${Math.round(row.inputTokens / 1000)}k in · low-value read ~${Math.round(row.lowValueRead / 1000)}k · ${row.effTokens !== undefined ? `${Math.round(row.effTokens / 1000)}k eff` : `$${row.costUsd.toFixed(3)}`}${row.denials || row.trims ? ` · ${row.denials} denied, ${row.trims} trimmed (~${Math.round(row.withheld / 1000)}k withheld)` : ""}\n`);
  });

  const outDir = join(REPO, "bench/ab-results");
  mkdirSync(outDir, { recursive: true });
  const outFile = join(outDir, `run-${Date.now()}.json`);
  writeFileSync(outFile, JSON.stringify({ agent: AGENT, model: MODEL, n: N, measuredAt: new Date().toISOString(), rows }, null, 2));
  console.log(`\nFull results: ${outFile}`);
  const broken = summarize(rows, tasks, MODEL, N);
  // --gate: a release check. Any task that passes with snout off and fails with it on fails the run.
  if (args.gate && broken.length) process.exitCode = 1;
}

/** Prints the comparison. `--summarize <results.json>` re-runs it on a saved file. */
function summarize(rows, tasks, model, n) {
  // Codex rows carry effective tokens instead of dollars; the comparison is the same.
  const eff = rows.some((r) => r.effTokens !== undefined);
  const K = eff ? "effTokens" : "costUsd";
  const money = (v) => (eff ? `${Math.round(v / 1000)}k` : `$${v.toFixed(eff ? 0 : 2)}`);
  console.log(`\nA/B, ${eff ? "codex" : "claude"}, model ${model}, n=${n}\n`);
  console.log(`  task      arm        pass    input tok (median)   low-value read   output   turns   ${eff ? "eff tok" : "cost"}`);
  const infra = rows.filter((r) => r.inputTokens === 0 && r.error);
  if (infra.length) console.log(`  ${infra.length} run(s) never reached the model (${infra[0].error.slice(0, 60)}…); excluded below.\n`);
  rows = rows.filter((r) => !infra.includes(r));
  for (const t of tasks) for (const a of ["off", "enforce"]) {
    const rs = rows.filter((r) => r.task === t && r.arm === a);
    if (!rs.length) continue;
    console.log(`  ${t.padEnd(9)} ${a.padEnd(9)} ${`${rs.filter((r) => r.pass).length}/${rs.length}`.padStart(5)} ${String(Math.round(median(rs.map((r) => r.inputTokens)))).padStart(18)} ${String(Math.round(median(rs.map((r) => r.lowValueRead ?? 0)))).padStart(16)} ${String(Math.round(median(rs.map((r) => r.outputTokens)))).padStart(8)} ${String(median(rs.map((r) => r.turns))).padStart(7)}   ${eff ? Math.round(median(rs.map((r) => r[K]))) : "$" + median(rs.map((r) => r[K])).toFixed(3)}`);
  }
  if (ARMS.includes("off") && ARMS.includes("enforce")) {
    const off = rows.filter((r) => r.arm === "off"), on = rows.filter((r) => r.arm === "enforce");
    const broken = tasks.filter((t) => off.some((r) => r.task === t && r.pass) && !on.some((r) => r.task === t && r.pass));
    const sum = (rs, k) => rs.reduce((x, r) => x + r[k], 0);
    console.log("");
    if (broken.length) console.log(`  BROKEN by enforce: ${broken.join(", ")} — passes with snout off, fails with it on.`);
    const pct = (a, b) => (b > 0 ? `${a <= b ? "-" : "+"}${Math.abs((1 - a / b) * 100).toFixed(1)}%` : "n/a");
    // Cost leads: most input tokens are cache reads billed at a tenth of the price, so a
    // summed token count overstates the turns a deny adds and understates the bulk it avoids.
    for (const [label, set] of [["bulk-path tasks", BULK], ["control tasks", tasks.filter((t) => !BULK.includes(t))]]) {
      const o = off.filter((r) => set.includes(r.task)), e = on.filter((r) => set.includes(r.task));
      if (!o.length || !e.length) continue;
      console.log(`  ${label.padEnd(16)} ${eff ? "eff tokens" : "cost"} ${pct(sum(e, K), sum(o, K))} (${money(sum(o, K))} → ${money(sum(e, K))}) · low-value read ~${Math.round(sum(o, "lowValueRead") / 1000)}k → ~${Math.round(sum(e, "lowValueRead") / 1000)}k · input tokens ${pct(sum(e, "inputTokens"), sum(o, "inputTokens"))}`);
    }
    console.log(`  all tasks        ${eff ? "eff tokens" : "cost"} ${pct(sum(on, K), sum(off, K))} (${money(sum(off, K))} → ${money(sum(on, K))}) · withheld by the gate ~${Math.round(sum(on, "withheld") / 1000)}k in ${sum(on, "denials")} denial(s) and ${sum(on, "trims") || 0} trim(s)`);
    console.log(`  Tasks passing:   off ${off.filter((r) => r.pass).length}/${off.length} · enforce ${on.filter((r) => r.pass).length}/${on.length}`);
    return broken;
  }
  return [];
}

