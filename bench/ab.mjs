function rng(seed) {
  let s = seed;
  return () => ((s = (s * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff);
}

function lockfile() {
  const r = rng(7);
  const pkgs = {};
  const names = ["left-pad", "chalk", "debug", "ms", "semver", "yargs", "minimist", "commander", "lodash.get", "uuid"];
  for (let i = 0; i < 900; i++) {
    const name = i < names.length ? names[i] : `dep-${i.toString(36)}-${Math.floor(r() * 1e6).toString(36)}`;
    const v = `${1 + Math.floor(r() * 9)}.${Math.floor(r() * 20)}.${Math.floor(r() * 30)}`;
    pkgs[`node_modules/${name}`] = {
      version: name === "left-pad" ? "1.3.0" : v,
      resolved: `https://registry.npmjs.org/${name}/-/${name}-${v}.tgz`,
      integrity: `sha512-${Buffer.from(String(r())).toString("base64").repeat(3).slice(0, 86)}==`,
      ...(r() > 0.6 ? { dependencies: { [`dep-${Math.floor(r() * 900).toString(36)}`]: `^${v}` } } : {}),
    };
  }
  return JSON.stringify({ name: "shopfront", version: "2.4.0", lockfileVersion: 3, requires: true, packages: { "": { name: "shopfront", version: "2.4.0", dependencies: { "left-pad": "^1.3.0", chalk: "^5.0.0" } }, ...pkgs } }, null, 2);
}

function minified(kb) {
  const r = rng(11);
  let s = "";
  while (s.length < kb * 1024) s += `function _${Math.floor(r() * 1e6).toString(36)}(a,b){return a${r() > 0.5 ? "+" : "*"}b|0}var q${Math.floor(r() * 1e4)}=[${[1, 2, 3].map(() => Math.floor(r() * 99)).join(",")}];`;
  return `/*! shopfront bundle */${s}\n`;
}

function generatedClient() {
  const ops = ["getUser", "listUsers", "getOrder", "listOrders", "getProduct", "listProducts", "createCart", "getCart"];
  let s = "// @generated by openapi-generator. DO NOT EDIT.\n// Source: api/openapi.yaml\n\n";
  for (let i = 0; i < 120; i++) {
    const op = ops[i % ops.length] + (i >= ops.length ? `V${Math.floor(i / ops.length)}` : "");
    s += `/** ${op}: generated request wrapper. */\nexport function ${op}(http, params = {}) {\n  const query = Object.entries(params).map(([k, v]) => \`\${k}=\${encodeURIComponent(v)}\`).join("&");\n  return http.request({ method: "GET", path: "/v1/${op.toLowerCase()}" + (query ? "?" + query : "") });\n}\n\n`;
  }
  return s;
}

/** A readable vendored library (~80 KB): the kind an agent opens to learn one function. */
function vendoredDecimal() {
  let s = "/*! decimal-lite v2.3.0 | MIT | vendored copy, do not modify */\n\n";
  s += "/**\n * Rounds `value` to `places` decimal places without binary floating-point error:\n * round(1.005, 2) === 1.01.\n */\nexport function round(value, places = 0) {\n  return Number(Math.round(Number(value + \"e\" + places)) + \"e-\" + places);\n}\n\n";
  const ops = ["add", "sub", "mul", "div", "mod", "pow", "abs", "neg", "cmp", "eq", "lt", "gt", "floor", "ceil", "trunc", "sign"];
  for (let i = 0; s.length < 80 * 1024; i++) {
    const name = `${ops[i % ops.length]}${i >= ops.length ? Math.floor(i / ops.length) : ""}`;
    s += `/**\n * ${name}: operates on decimal strings of arbitrary precision.\n * @param {string|number} a\n * @param {string|number} b\n * @returns {string}\n */\nexport function ${name}(a, b = 0) {\n  const x = String(a).split("."), y = String(b).split(".");\n  const scale = Math.max((x[1] || "").length, (y[1] || "").length);\n  const ax = BigInt(x[0] + (x[1] || "").padEnd(scale, "0"));\n  const by = BigInt(y[0] + (y[1] || "").padEnd(scale, "0"));\n  const r = ax ${["+", "-", "*"][i % 3]} by;\n  return scale ? (r / 10n ** BigInt(scale)) + "." + String(r % 10n ** BigInt(scale)).padStart(scale, "0") : String(r);\n}\n\n`;
  }
  return s;
}

