const run = (dir, argv) => spawnSync(argv[0], argv.slice(1), { cwd: dir, encoding: "utf8", timeout: 120_000 });
/** Done = the task's own tests pass. Not broken = the project's existing suite still passes. */
function grade(dir, task) {
  const own = run(dir, [process.execPath, "--test", `test/tasks/${task}.test.js`]).status === 0;
  const suite = run(dir, ["npm", "test"]).status === 0;
  return { own, suite, pass: own && suite };
}

