#!/usr/bin/env node
/**
 * Long-session A/B: multi-step coding tasks in a larger, realistic project, run by a real
 * headless Claude Code with Snout off and with Snout enforcing.
 *
 * The short benchmark (bench/ab.mjs) runs 5–8 turn tasks, where Claude Code's own fixed
 * instructions are half of every request and the savings ceiling is low. Real sessions run
 * longer, re-read files, search the tree and rerun test suites, and every token kept out of an
 * early turn is also kept out of every later turn's re-read. This suite measures that.
 *
 * The fixture ("shopfront") is generated fresh per run: ~30 source modules, a test suite of
 * ~250 passing tests, and the bulk real projects carry: a large lockfile, a minified bundle, a
 * generated API client, a vendored library, data fixtures, a long changelog and coverage output.
 *
 * Quality is graded twice per task: the task's own tests must pass, AND the project's existing
 * suite must still pass. A run that saves tokens by breaking something is a failure.
 *
 * Usage:
 *   node bench/long.mjs --n 1 --tasks tax          # smoke
 *   node bench/long.mjs --n 3 --model haiku        # full run
 *   node bench/long.mjs --summarize bench/ab-results/long-<ts>.json
 *   options: --arms off,enforce  --budget 1.50  --keep
 */
