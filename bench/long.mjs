function runOne(task, arm) {
  const dir = makeFixture(arm, task);
  const started = Date.now();
  const r = spawnSync(
    "claude",
    [
      "-p", TASKS[task],
      "--output-format", "json",
      "--model", MODEL,
      "--setting-sources", "project",
      "--strict-mcp-config",
      "--mcp-config", join(dir, ".mcp.json"),
      "--permission-mode", "acceptEdits",
      "--allowedTools", "Read", "Edit", "Write", "Grep", "Glob", "Bash(node:*)", "Bash(npm test:*)", "Bash(npm run:*)", "Bash(ls:*)", "Bash(cat:*)", "Bash(grep:*)", "Bash(rg:*)", "Bash(find:*)", "Bash(head:*)", "Bash(tail:*)", "Bash(wc:*)", "mcp__tracker__list_issues", "mcp__tracker__get_issue", "mcp__wiki__search", "mcp__wiki__get_page",
      "--max-budget-usd", BUDGET,
    ],
    { cwd: dir, encoding: "utf8", timeout: 20 * 60_000, env: { ...process.env, SNOUT_MODE: arm === "off" ? "observe" : "enforce" }, maxBuffer: 64 * 1024 * 1024 },
  );
  let out = {};
  try { out = JSON.parse(r.stdout); } catch { out = { is_error: true, result: (r.stderr || r.stdout || "").slice(0, 300) }; }
  const u = out.usage ?? {};
  const byRule = {};
  const mcp = {};
  let withheld = 0;
  const ledger = join(dir, ".snout/ledger.jsonl");
  if (existsSync(ledger)) {
    for (const l of readFileSync(ledger, "utf8").split("\n")) {
      if (!l.trim()) continue;
      const d = JSON.parse(l);
      const kept = d.trimmed || d.decision === "deny" ? d.tokensAvoidedEst || 0 : 0;
      const server = typeof d.tool === "string" && d.tool.startsWith("mcp__") ? d.tool.split("__")[1] : null;
      if (server) {
        mcp[server] ??= { calls: 0, inContext: 0, saved: 0 };
        mcp[server].calls += 1;
        mcp[server].inContext += d.tokensReadEst || 0;
        mcp[server].saved += kept;
      }
      if (!kept) continue;
      withheld += kept;
      byRule[d.rule] = (byRule[d.rule] ?? 0) + kept;
    }
  }
  const g = out.is_error ? { own: false, suite: false, pass: false } : grade(dir, task);
  const row = {
    task, arm, ...g,
    error: out.is_error ? String(out.result ?? out.subtype ?? "error").slice(0, 200) : undefined,
    uncached: u.input_tokens ?? 0,
    cacheWrite: u.cache_creation_input_tokens ?? 0,
    cacheRead: u.cache_read_input_tokens ?? 0,
    inputTokens: (u.input_tokens ?? 0) + (u.cache_creation_input_tokens ?? 0) + (u.cache_read_input_tokens ?? 0),
    outputTokens: u.output_tokens ?? 0,
    turns: out.num_turns ?? 0,
    costUsd: out.total_cost_usd ?? 0,
    withheld,
    byRule,
    mcp,
    seconds: Math.round((Date.now() - started) / 1000),
  };
  if (!row.pass) row.final = String(out.result ?? "").slice(0, 500);
  if (!args.keep) rmSync(dir, { recursive: true, force: true });
  else row.dir = dir;
  return row;
}

function summarize(rows, model, n) {
  const pct = (a, b) => (b > 0 ? `${a <= b ? "−" : "+"}${Math.abs((1 - a / b) * 100).toFixed(1)}%` : "n/a");
  const sum = (rs, k) => rs.reduce((x, r) => x + (r[k] ?? 0), 0);
  const tasks = [...new Set(rows.map((r) => r.task))];
  console.log(`\nLong-session A/B, claude ${model}, n=${n}\n`);
  console.log("  task       arm       done  suite ok   input tok   output   turns     cost");
  for (const t of tasks) for (const a of ["off", "enforce", "concise"]) {
    const rs = rows.filter((r) => r.task === t && r.arm === a);
    if (!rs.length) continue;
    const avg = (k) => sum(rs, k) / rs.length;
    console.log(`  ${t.padEnd(10)} ${a.padEnd(9)} ${`${rs.filter((r) => r.own).length}/${rs.length}`.padStart(4)} ${`${rs.filter((r) => r.suite).length}/${rs.length}`.padStart(9)} ${String(Math.round(avg("inputTokens"))).padStart(11)} ${String(Math.round(avg("outputTokens"))).padStart(8)} ${avg("turns").toFixed(1).padStart(7)}   $${avg("costUsd").toFixed(3)}`);
  }
  const off = rows.filter((r) => r.arm === "off");
  for (const arm of ["enforce", "concise"]) {
    const on = rows.filter((r) => r.arm === arm);
    if (off.length && on.length) compare(off, on, arm, sum, pct, tasks);
  }
}

function compare(off, on, arm, sum, pct, tasks) {
  // Compare like with like: only tasks that ran in both arms.
  const paired = new Set(on.map((r) => r.task).filter((t) => off.some((r) => r.task === t)));
  off = off.filter((r) => paired.has(r.task));
  on = on.filter((r) => paired.has(r.task));
  console.log(`\n  ${arm} vs off (${paired.size} task${paired.size === 1 ? "" : "s"} run in both)`);
  console.log("");
  console.log(`  cost            ${pct(sum(on, "costUsd"), sum(off, "costUsd"))}   ($${sum(off, "costUsd").toFixed(2)} → $${sum(on, "costUsd").toFixed(2)})`);
  console.log(`  input tokens    ${pct(sum(on, "inputTokens"), sum(off, "inputTokens"))}`);
  console.log(`  output tokens   ${pct(sum(on, "outputTokens"), sum(off, "outputTokens"))}`);
  console.log(`  turns           ${pct(sum(on, "turns"), sum(off, "turns"))}`);
  console.log(`  passing         off ${off.filter((r) => r.pass).length}/${off.length} · enforce ${on.filter((r) => r.pass).length}/${on.length}   (done AND existing suite still green)`);
  const rules = {};
  for (const r of on) for (const [k, v] of Object.entries(r.byRule ?? {})) rules[k] = (rules[k] ?? 0) + v;
  const servers = {};
  for (const r of on) for (const [k, v] of Object.entries(r.mcp ?? {})) { servers[k] ??= { calls: 0, inContext: 0, saved: 0 }; for (const f of ["calls", "inContext", "saved"]) servers[k][f] += v[f]; }
  if (Object.keys(servers).length) console.log(`  MCP servers     ${Object.entries(servers).map(([k, v]) => `${k}: ${v.calls} calls, ~${Math.round(v.saved / 1000)}k saved of ~${Math.round((v.saved + v.inContext) / 1000)}k (${v.saved + v.inContext ? Math.round((v.saved / (v.saved + v.inContext)) * 100) : 0}%)`).join(" · ")}`);
  console.log(`  kept out by     ${Object.entries(rules).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ~${Math.round(v / 1000)}k`).join(" · ") || "nothing"}`);
  // Only tasks that ran in both arms: a run that never happened is not a failure.
  const broken = tasks.filter((t) => on.some((r) => r.task === t) && off.some((r) => r.task === t && r.pass) && !on.some((r) => r.task === t && r.pass));
  if (broken.length) console.log(`  BROKEN by enforce: ${broken.join(", ")}`);
}

function main() {
  if (typeof args.summarize === "string") {
    const saved = JSON.parse(readFileSync(args.summarize, "utf8"));
    return summarize(saved.rows, saved.model, saved.n);
  }
  const tasks = typeof args.tasks === "string" ? args.tasks.split(",") : Object.keys(TASKS);
  const plan = [];
  for (let i = 0; i < N; i++) for (const t of tasks) for (const a of ARMS) plan.push([t, a]);
  console.error(`${plan.length} run(s): ${tasks.length} task(s) × ${ARMS.length} arm(s) × ${N}, model ${MODEL}, cap $${BUDGET}/run`);
  const rows = [];
  const outDir = join(REPO, "bench/ab-results");
  mkdirSync(outDir, { recursive: true });
  const outFile = join(outDir, `long-${Date.now()}.json`);
  plan.forEach(([t, a], i) => {
    process.stderr.write(`[${i + 1}/${plan.length}] ${t} · ${a} ... `);
    const row = runOne(t, a);
    rows.push(row);
    // Saved after every run, so an interrupted benchmark keeps what it measured.
    writeFileSync(outFile, JSON.stringify({ model: MODEL, n: N, measuredAt: new Date().toISOString(), rows }, null, 2));
    process.stderr.write(`${row.pass ? "pass" : `FAIL(${row.own ? "" : "task "}${row.suite ? "" : "suite"})`} · ${Math.round(row.inputTokens / 1000)}k in · ${row.outputTokens} out · ${row.turns} turns · $${row.costUsd.toFixed(3)}${row.withheld ? ` · ~${Math.round(row.withheld / 1000)}k kept out` : ""}\n`);
  });
  console.log(`\nFull results: ${outFile}`);
  summarize(rows, MODEL, N);
}

