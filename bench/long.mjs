/** A night of production logs: thousands of routine lines, one real error near the end. */
function appLog() {
  const lines = [];
  for (let i = 0; i < 4000; i++) {
    const t = new Date(Date.UTC(2026, 9, 1, 22, 0, 0) + i * 9000).toISOString();
    if (i === 900) lines.push(`${t} WARN payments retry scheduled for refund r_${i} (gateway timeout, will retry)`);
    else if (i === 3940) lines.push(`${t} ERROR checkout failed: TypeError: Cannot read properties of null (reading 'percent')\n    at couponDiscount (src/pricing/coupons.js:8:51)\n    at createOrder (src/orders/order.js:15:20)\n    note: request body had coupons [null, {"percent":10}] from the mobile app`);
    else lines.push(`${t} INFO ${pick(["GET /api/cart", "POST /api/orders", "GET /api/products", "GET /api/orders"])} ${pick([200, 200, 200, 201, 304])} ${10 + (i % 90)}ms user=u_${i % 500}`);
  }
  return lines.join("\n") + "\n";
}

